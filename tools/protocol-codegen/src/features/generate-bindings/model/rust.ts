import { SERVER_FLAGS } from "@masseater.dev/aredoko-protocol";
import type { Effect2rsInput } from "@masseater.dev/effect2rs";
import { Effect, Record, pipe } from "effect";

export interface RustOutput extends Effect2rsInput {
  readonly output: string;
}

const HEADER = "// @generated by tools/protocol-codegen. Do not edit.";

const DESKTOP_DERIVE = ["specta::Type", "schemars::JsonSchema"];

const aredokoRust: RustOutput = {
  output: "../../apps/aredoko-desktop/src-tauri/src/protocol.rs",
  header: HEADER,
  definitions: pipe(
    SERVER_FLAGS,
    Record.mapEntries((flag, key) => [`${key}Flag`, `--${flag}`]),
  ),
};

const yohakuRust = Effect.gen(function* yohakuRust() {
  const models = yield* Effect.promise(() => import("@masseater.dev/yohaku-protocol"));
  const sync = yield* Effect.promise(() => import("@masseater.dev/yohaku-protocol/sync"));
  const output: RustOutput = {
    output: "../../apps/yohaku-desktop/src-tauri/src/protocol.rs",
    header: HEADER,
    derive: DESKTOP_DERIVE,
    definitions: { ...models, ...sync },
  };
  return output;
});

const MEDIA_NOTES_TYPES = ["Site", "Source", "Media", "Opened", "Saved", "McpAccess"] as const;

const fromMediaNotes = Record.fromIterableWith(MEDIA_NOTES_TYPES, (name) => [
  name,
  `media_notes::protocol::${name}`,
]);

const mediaNotesRust = Effect.gen(function* mediaNotesRust() {
  const definitions = yield* Effect.promise(() => import("@masseater.dev/media-notes-protocol"));
  const output: RustOutput = {
    output: "../../libs/media-notes/src/protocol.rs",
    header: HEADER,
    derive: DESKTOP_DERIVE,
    definitions,
  };
  return output;
});

const shirushiRust = Effect.gen(function* shirushiRust() {
  const definitions = yield* Effect.promise(() => import("@masseater.dev/shirushi-protocol"));
  const output: RustOutput = {
    output: "../../apps/shirushi/src-tauri/src/protocol.rs",
    header: HEADER,
    derive: DESKTOP_DERIVE,
    definitions,
    external: fromMediaNotes,
  };
  return output;
});

const akapenRust = Effect.gen(function* akapenRust() {
  const definitions = yield* Effect.promise(() => import("@masseater.dev/akapen-protocol"));
  const output: RustOutput = {
    output: "../../apps/akapen/src-tauri/src/protocol.rs",
    header: HEADER,
    derive: DESKTOP_DERIVE,
    definitions,
    external: fromMediaNotes,
  };
  return output;
});

export const rustOutputs = Effect.all([
  Effect.succeed(aredokoRust),
  yohakuRust,
  mediaNotesRust,
  shirushiRust,
  akapenRust,
]);
