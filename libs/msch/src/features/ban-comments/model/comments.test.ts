import { layer } from "@effect/vitest";
import { Array as Arr, Effect, pipe } from "effect";
import { expect } from "vite-plus/test";

import { sortProblems } from "#/shared/lib/problem.ts";
import { RepositoryFiles } from "#/shared/lib/repository-files.ts";
import { fixtureLayer, gitRepositoryWith } from "#/shared/lib/repository.test.support.ts";

import { checkComments } from "./comments.ts";

const SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1";

const findingsFor = Effect.fn("findingsFor")(function* findingsFor(
  files: Readonly<Record<string, string>>,
) {
  const repositoryFiles = yield* RepositoryFiles;
  const root = yield* gitRepositoryWith(files);
  const problems = yield* checkComments(root);
  return pipe(
    sortProblems(problems),
    Arr.map(
      (problem) =>
        `${repositoryFiles.relative(root, problem.file)}:${String(problem.line)}:${String(problem.column)} ${problem.rule}`,
    ),
  );
});

const flagsCommentsInEveryLanguage = Effect.gen(function* flagsCommentsInEveryLanguage() {
  const findings = yield* findingsFor({
    "src/main.ts": 'const URL_TEXT = "https://example.com";\n// says what the code says\n',
    "src/view.tsx": "const View = () => <div>{/* hidden */}</div>;\n",
    "src/lib.rs": '/// Explains the function.\nfn main() { let text = "// not a comment"; }\n',
    "src/Mod.cs": "class Mod { int Count; // why it counts\n}\n",
    "scripts/run.sh": '#!/usr/bin/env bash\n# what it runs\necho "# kept"\n',
    "scripts/run.ps1": "# what it runs\nWrite-Output 'x'\n",
    "pages/index.html":
      "<!-- page -->\n<style>/* layout */ a { color: red; }</style>\n<script type=\"module\">\n  // step\n  const url = 'https://a//b';\n</script>\n",
    "build/Directory.Build.props": "<Project>\n  <!-- shared -->\n</Project>\n",
    "shaders/glow.frag": "// note: kept by the allow list\n/* glow */\nvoid main() {}\n",
    ".github/workflows/ci.yml": `jobs:\n  a:\n    steps:\n      - uses: actions/checkout@${SHA} # v7.0.1\n      # check out first\n      - run: echo "#1"\n`,
    "mise.toml": '# tools\n[tools]\nnode = "26"\n',
    "migrations/0001.sql":
      "CREATE TABLE t (id integer);\n--> statement-breakpoint\n-- adds the index\nCREATE INDEX i ON t (id);\n",
    "container/Dockerfile": "# syntax=docker/dockerfile:1\n# base image\nFROM node:26\n",
    "vite.config.ts": 'export default { msch: { comments: { allow: ["note:"] } } };\n',
  });
  expect(findings).toStrictEqual([
    ".github/workflows/ci.yml:5:7 comment",
    "build/Directory.Build.props:2:3 comment",
    "container/Dockerfile:2:1 comment",
    "migrations/0001.sql:3:1 comment",
    "mise.toml:1:1 comment",
    "pages/index.html:1:1 comment",
    "pages/index.html:2:8 comment",
    "pages/index.html:4:3 comment",
    "scripts/run.ps1:1:1 comment",
    "scripts/run.sh:2:1 comment",
    "shaders/glow.frag:2:1 comment",
    "src/Mod.cs:1:24 comment",
    "src/lib.rs:1:1 comment",
    "src/main.ts:2:1 comment",
    "src/view.tsx:1:26 comment",
  ]);
});

const passesDirectivesAndSkippedFiles = Effect.gen(function* passesDirectivesAndSkippedFiles() {
  const findings = yield* findingsFor({
    "src/main.ts":
      "// oxlint-disable-next-line eslint/no-console -- prints the report\nconsole.log(1);\n/** @internal */\nconst A = 1;\n/** @msch status */\nconst B = 2;\n",
    "src/cli.ts": "#!/usr/bin/env node\nconst C = 3;\n",
    "src/env.d.ts": '/// <reference types="vite/client" />\n',
    "src/fetch.ts":
      "// fallow-ignore-next-line security-sink -- fixed origin\nfetch(URL);\n/* v8 ignore start */\nrun();\n/* v8 ignore stop */\nawait import(/* @vite-ignore */ name);\n",
    "src/fetch.test.ts": "// @vitest-environment node\nconst D = 4;\n",
    "scripts/lint.sh": "# shellcheck disable=SC2086\necho $A\n",
    "src/Protocol.g.cs": "// <auto-generated />\nclass P {}\n",
    "upstream/copied.ts": "// kept as the upstream wrote it\n",
    ".gitattributes": "*.g.cs linguist-generated\n",
    "vite.config.ts": 'export default { lint: { ignorePatterns: ["upstream/**"] } };\n',
  });
  expect(findings).toStrictEqual([]);
});

layer(fixtureLayer)("comments", (it) => {
  it.effect(
    "flags comments in code, markup, configuration, and queries",
    () => flagsCommentsInEveryLanguage,
  );
  it.effect(
    "passes tool directives, generated files, and files the lint ignores",
    () => passesDirectivesAndSkippedFiles,
  );
});
