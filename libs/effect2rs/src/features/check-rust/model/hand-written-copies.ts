import { Array as Arr, Schema, pipe } from "effect";

import type { Copy } from "./copies.ts";

const taggedError = Schema.TaggedError;

const CopyLocation = Schema.Struct({
  path: Schema.String,
  line: Schema.Finite,
  name: Schema.String,
});

export class HandWrittenCopies extends taggedError<
  HandWrittenCopies,
  { readonly brand: unique symbol }
>()("HandWrittenCopies", { copies: Schema.Array(CopyLocation), message: Schema.String }) {}

export const handWrittenCopies = (copies: readonly Copy[]): HandWrittenCopies => {
  const places = pipe(
    copies,
    Arr.map(({ path, line, name }) => `${path}:${line} declares ${name}`),
    Arr.join("\n"),
  );
  return HandWrittenCopies.make({
    copies,
    message: `These Rust items are generated by effect2rs, so declare them only in the generated file and import them from there:\n${places}`,
  });
};
