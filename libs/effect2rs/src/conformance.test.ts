import { NodeServices } from "@effect/platform-node";
import { expect, layer } from "@effect/vitest";
import {
  Array as Arr,
  Effect,
  Exit,
  FileSystem,
  Match,
  Option,
  Record,
  Schema,
  pipe,
} from "effect";

import { Samples, conformance } from "./conformance.test.support.ts";
import { effect2rs } from "./index.ts";

const HEADER = "// @generated by libs/effect2rs/src/conformance.test.ts. Do not edit.";
const SAMPLES = new URL("../conformance/samples.json", import.meta.url);

const Invalid = Schema.Struct({
  reason: Schema.String,
  set: Schema.optionalKey(Schema.Record(Schema.String, Schema.Unknown)),
  remove: Schema.optionalKey(Schema.String),
});

const Fixture = Schema.fromJsonString(
  Schema.Struct({ valid: Schema.toEncoded(Samples), invalid: Schema.Array(Invalid) }),
);

type Encoded = typeof Samples.Encoded;

const FIRST = 0;

const decodeSamples = Schema.decodeUnknownExit(Samples);

const fixture = Effect.gen(function* fixture() {
  const fileSystem = yield* FileSystem.FileSystem;
  const text = yield* fileSystem.readFileString(SAMPLES.pathname);
  return yield* Schema.decodeEffect(Fixture)(text);
});

const withoutKey =
  (remove: string | undefined) =>
  (point: Readonly<Record<string, unknown>>): Readonly<Record<string, unknown>> =>
    pipe(
      Option.fromNullishOr(remove),
      Option.match({
        onNone: () => point,
        onSome: (key) => pipe(point, Record.remove(key)),
      }),
    );

const mutated =
  (valid: Encoded) =>
  ({ set, remove }: typeof Invalid.Type): unknown => {
    const points = pipe(
      valid.points,
      Arr.map((point, index) =>
        Match.value(index).pipe(
          Match.when(FIRST, () => withoutKey(remove)({ ...point, ...set })),
          Match.orElse(() => point),
        ),
      ),
    );
    return { ...valid, points };
  };

layer(NodeServices.layer)("conformance", (it) => {
  it.effect("the conformance crate compiles the Rust generated from the fixture schemas", () =>
    Effect.gen(function* body() {
      const source = yield* effect2rs({
        header: HEADER,
        derive: ["specta::Type", "schemars::JsonSchema"],
        definitions: conformance,
      });
      yield* Effect.promise(() => expect(source).toMatchFileSnapshot("../conformance/protocol.rs"));
    }),
  );

  it.effect("Effect Schema accepts the samples that the Rust side round-trips", () =>
    Effect.gen(function* body() {
      const { valid } = yield* fixture;
      expect(Exit.isSuccess(decodeSamples(valid))).toBe(true);
    }),
  );

  it.effect("Effect Schema rejects every sample that the Rust side must reject", () =>
    Effect.gen(function* body() {
      const { valid, invalid } = yield* fixture;
      const accepted = pipe(
        invalid,
        Arr.filter((sample) => Exit.isSuccess(decodeSamples(mutated(valid)(sample)))),
        Arr.map(({ reason }) => reason),
      );
      expect(accepted).toStrictEqual([]);
    }),
  );
});
