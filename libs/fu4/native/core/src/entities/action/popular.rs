use std::collections::{BTreeMap, HashMap, HashSet};
use std::sync::LazyLock;

use serde::Deserialize;

use super::{ActionInput, ActionMetadata, ActionRuns};

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct InputData {
    name: String,
    required: bool,
    deprecated: bool,
    deprecation_message: String,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct ActionData {
    name: String,
    inputs: BTreeMap<String, InputData>,
    outputs: BTreeMap<String, serde_json::Value>,
    skip_inputs: bool,
    skip_outputs: bool,
    using: String,
}

#[derive(Deserialize)]
struct Data {
    actions: BTreeMap<String, ActionData>,
    outdated: Vec<String>,
}

struct Table {
    actions: HashMap<String, ActionMetadata>,
    outdated: HashSet<String>,
}

static TABLE: LazyLock<Table> = LazyLock::new(|| {
    let data: Data = serde_json::from_str(include_str!("../../../data/popular-actions.json"))
        .expect("popular-actions.json is generated by bin/generate-data.ts");
    let actions = data
        .actions
        .into_iter()
        .map(|(spec, action)| {
            let inputs = action
                .inputs
                .into_values()
                .map(|input| {
                    (
                        input.name.to_lowercase(),
                        ActionInput {
                            name: input.name,
                            required: input.required,
                            deprecated: input.deprecated,
                            deprecation_message: input.deprecation_message,
                        },
                    )
                })
                .collect();
            let outputs = action
                .outputs
                .into_keys()
                .map(|name| (name.to_lowercase(), name))
                .collect();
            let metadata = ActionMetadata {
                name: action.name,
                inputs,
                outputs,
                skip_inputs: action.skip_inputs,
                skip_outputs: action.skip_outputs,
                runs: ActionRuns {
                    using: action.using,
                    ..ActionRuns::default()
                },
                ..ActionMetadata::default()
            };
            (spec, metadata)
        })
        .collect();
    Table {
        actions,
        outdated: data.outdated.into_iter().collect(),
    }
});

#[must_use]
pub fn popular(spec: &str) -> Option<&'static ActionMetadata> {
    TABLE.actions.get(spec)
}

#[must_use]
pub fn is_outdated(spec: &str) -> bool {
    TABLE.outdated.contains(spec)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn loads_generated_data() {
        let checkout = popular("actions/checkout@v4").expect("checkout is popular");
        assert!(checkout.inputs.contains_key("fetch-depth"));
        assert!(is_outdated("8398a7/action-slack@v1"));
    }
}
