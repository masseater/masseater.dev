use std::collections::BTreeMap;
use std::sync::OnceLock;

use serde::Deserialize;

#[derive(Debug, Deserialize)]
pub struct Availability {
    pub contexts: Vec<String>,
    pub functions: Vec<String>,
}

pub struct Table {
    pub keys: BTreeMap<String, Availability>,
    pub special: BTreeMap<String, Vec<String>>,
}

static TABLE: OnceLock<Table> = OnceLock::new();

#[must_use]
pub fn table() -> &'static Table {
    TABLE.get_or_init(|| {
        let keys: BTreeMap<String, Availability> =
            serde_json::from_str(include_str!("../../../data/availability.json"))
                .expect("availability.json is generated by bin/generate-data.ts");
        let mut special: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for (key, availability) in &keys {
            for function in &availability.functions {
                special
                    .entry(function.clone())
                    .or_default()
                    .push(key.clone());
            }
        }
        Table { keys, special }
    })
}

#[must_use]
pub fn workflow_key(key: &str) -> Option<&'static Availability> {
    table().keys.get(key)
}
