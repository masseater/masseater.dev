use std::collections::BTreeMap;
use std::sync::LazyLock;

use serde_json::Value;

use super::types::{ExprType, ObjectType};

static CONTEXTS: LazyLock<BTreeMap<String, Value>> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../data/contexts.json"))
        .expect("contexts.json is generated by bin/generate-data.ts")
});

fn type_of(value: &Value) -> ExprType {
    match value {
        Value::Object(props) => {
            let placeholder = props.iter().find(|(key, _)| key.starts_with('<'));
            if let Some((_, elem)) = placeholder {
                return ExprType::Object(ObjectType::map_of(type_of(elem)));
            }
            ExprType::Object(ObjectType::strict_with(
                props
                    .iter()
                    .map(|(key, prop)| (key.to_lowercase(), type_of(prop)))
                    .collect(),
            ))
        }
        Value::String(name) => match name.as_str() {
            "string" => ExprType::String,
            "number" => ExprType::Number,
            "boolean" => ExprType::Bool,
            _ => ExprType::Object(ObjectType::loose()),
        },
        _ => ExprType::Any,
    }
}

#[must_use]
pub fn documented(name: &str) -> ExprType {
    CONTEXTS
        .get(name)
        .map_or(ExprType::Object(ObjectType::strict()), type_of)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builds_types_from_the_documented_properties() {
        let ExprType::Object(job) = documented("job") else {
            panic!("job is an object");
        };
        assert_eq!(job.props.get("status"), Some(&ExprType::String));
        let Some(ExprType::Object(services)) = job.props.get("services") else {
            panic!("services is an object");
        };
        assert!(!services.is_strict());
        let ExprType::Object(github) = documented("github") else {
            panic!("github is an object");
        };
        assert!(github.props.contains_key("repositoryurl"));
        assert!(github.props.contains_key("step_summary"));
    }
}
