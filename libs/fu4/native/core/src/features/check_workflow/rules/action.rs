use std::path::Path;
use std::sync::{Arc, LazyLock};

use regex::Regex;
use serde::Deserialize;

use crate::entities::action::{ActionMetadata, ActionRuns, display_path, is_outdated, popular};
use crate::entities::workflow::{Exec, ExecAction, Step};
use crate::features::check_workflow::{Project, Report, Rule};
use crate::shared::text::{quote, sorted_quotes};
use crate::shared::yaml::Pos;

#[derive(Deserialize)]
struct ActionData {
    colors: Vec<String>,
    icons: Vec<String>,
    runtimes: Vec<String>,
}

static DATA: LazyLock<ActionData> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../../data/action.json"))
        .expect("action.json is generated by bin/generate-data.ts")
});

static NEWLINE_WITH_INDENT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\s*\r?\n\s*").expect("valid regex"));

const DOCS: &str =
    "https://docs.github.com/en/actions/creating-actions/metadata-syntax-for-github-actions";

fn on_registry(image: &str) -> bool {
    ["docker://", "gcr.io/", "pkg.dev/", "ghcr.io/", "docker.io/"]
        .iter()
        .any(|prefix| image.starts_with(prefix))
}

fn runtimes() -> String {
    let mut names: Vec<&str> = ["composite", "docker"]
        .into_iter()
        .chain(DATA.runtimes.iter().map(String::as_str))
        .collect();
    names.sort_unstable();
    let quoted: Vec<String> = names.iter().map(|n| quote(n)).collect();
    match quoted.split_last() {
        Some((last, rest)) if !rest.is_empty() => format!("{}, and {last}", rest.join(", ")),
        _ => quoted.join(""),
    }
}

pub struct Action {
    report: Report,
    project: Option<Arc<Project>>,
}

impl Action {
    pub fn new(project: Option<Arc<Project>>) -> Self {
        Self {
            report: Report::default(),
            project,
        }
    }

    fn invalid_format(&mut self, pos: Pos, spec: &str, why: &str) {
        self.error(
            pos,
            format!(
                "specifying action {} in invalid format because {why}. available formats are \"{{owner}}/{{repo}}@{{ref}}\" or \"{{owner}}/{{repo}}/{{path}}@{{ref}}\"",
                quote(spec)
            ),
        );
    }

    fn check_repo(&mut self, spec: &str, exec: &ExecAction, pos: Pos) {
        let Some((path, reference)) = spec.split_once('@') else {
            self.invalid_format(pos, spec, "ref is missing");
            return;
        };
        let Some((owner, rest)) = path.split_once('/') else {
            self.invalid_format(pos, spec, "owner is missing");
            return;
        };
        let repo = rest.split('/').next().unwrap_or_default();
        if owner.is_empty() || repo.is_empty() || reference.is_empty() {
            self.invalid_format(pos, spec, "owner and repo and ref should not be empty");
        }
        let Some(metadata) = popular(spec) else {
            if is_outdated(spec) {
                self.error(
                    pos,
                    format!(
                        "the runner of {} action is too old to run on GitHub Actions. update the action's version to fix this issue",
                        quote(spec)
                    ),
                );
            }
            return;
        };
        if metadata.skip_inputs {
            return;
        }
        self.check_inputs(metadata, exec, pos, &quote(spec));
    }

    fn check_docker(&mut self, uri: &str, pos: Pos) {
        let rest = &uri["docker://".len()..];
        if let Some(index) = rest.find(':')
            && rest[index + 1..].is_empty()
        {
            let image = &uri[.."docker://".len() + index];
            self.error(
                pos,
                format!("tag of Docker action should not be empty: {}", quote(image)),
            );
        }
    }

    fn check_local(&mut self, spec: &str, exec: &ExecAction, pos: Pos) {
        let Some(project) = self.project.clone() else {
            return;
        };
        match project.actions.find(&project.root, spec) {
            Err(message) => self.error(pos, message),
            Ok(None) => {}
            Ok(Some(found)) => {
                if !found.cached {
                    self.check_metadata(&found.metadata, pos);
                }
                let describe =
                    format!("{} defined at {}", quote(&found.metadata.name), quote(spec));
                self.check_inputs(&found.metadata, exec, pos, &describe);
            }
        }
    }

    fn check_metadata(&mut self, meta: &ActionMetadata, pos: Pos) {
        let path = quote(&display_path(&meta.path()));
        if meta.name.is_empty() {
            self.error(pos, format!("name is required in action metadata {path}"));
        }
        let name = quote(&meta.name);
        if meta.description.is_empty() {
            self.error(
                pos,
                format!("description is required in metadata of {name} action at {path}"),
            );
        }
        let icon = &meta.branding.icon;
        if !icon.is_empty() && !DATA.icons.contains(&icon.to_lowercase()) {
            self.error(
                pos,
                format!(
                    "incorrect icon name {} at branding.icon in metadata of {name} action at {path}. see the official document to know the exhaustive list of supported icons: {DOCS}#brandingicon",
                    quote(icon)
                ),
            );
        }
        let color = &meta.branding.color;
        if !color.is_empty() && !DATA.colors.contains(&color.to_lowercase()) {
            self.error(
                pos,
                format!(
                    "incorrect color {} at branding.icon in metadata of {name} action at {path}. see the official document to know the exhaustive list of supported colors: {DOCS}#brandingcolor",
                    quote(color)
                ),
            );
        }
        for input in meta.inputs.values() {
            if input.deprecated && input.deprecation_message.is_empty() {
                self.error(
                    pos,
                    format!(
                        "input {} is deprecated but \"deprecationMessage\" is empty in metadata of {name} action at {path}",
                        quote(&input.name)
                    ),
                );
            }
        }
        self.check_runs(meta, pos);
    }

    fn check_runs(&mut self, meta: &ActionMetadata, pos: Pos) {
        let dir = display_path(&meta.dir);
        let runs = &meta.runs;
        let local = Local {
            dir: &dir,
            base: &meta.dir,
            name: &meta.name,
            pos,
        };
        match runs.using.as_str() {
            "" => self.error(
                pos,
                format!(
                    "\"runs.using\" is missing in local action {} defined at {}",
                    quote(&meta.name),
                    quote(&dir)
                ),
            ),
            "docker" => self.check_docker_runs(runs, &local),
            "composite" => self.check_composite_runs(runs, &local),
            using if DATA.runtimes.iter().any(|r| r == using) => {
                self.check_javascript_runs(runs, &local);
            }
            using => {
                self.error(
                    pos,
                    format!(
                        "invalid runner name {} at runs.using in {} action defined at {}. valid runners are {}. see {DOCS}#runs",
                        quote(using),
                        quote(&meta.name),
                        quote(&dir),
                        runtimes()
                    ),
                );
                if using.starts_with("node") {
                    self.check_javascript_runs(runs, &local);
                }
            }
        }
    }

    fn missing_prop(&mut self, local: &Local, prop: &str, ty: &str) {
        self.error(
            local.pos,
            format!(
                "{} is required in \"runs\" section because {} is a {ty} action. the action is defined at {}",
                quote(prop),
                quote(local.name),
                quote(local.dir)
            ),
        );
    }

    fn invalid_props(&mut self, runs: &ActionRuns, local: &Local, ty: &str, props: &[&str]) {
        for prop in props {
            let set = match *prop {
                "main" => !runs.main.is_empty(),
                "pre" => !runs.pre.is_empty(),
                "pre-if" => !runs.pre_if.is_empty(),
                "post" => !runs.post.is_empty(),
                "post-if" => !runs.post_if.is_empty(),
                "steps" => runs.steps.is_some_and(|n| n > 0),
                "image" => !runs.image.is_empty(),
                "pre-entrypoint" => !runs.pre_entrypoint.is_empty(),
                "entrypoint" => !runs.entrypoint.is_empty(),
                "post-entrypoint" => !runs.post_entrypoint.is_empty(),
                "args" => runs.args,
                "env" => runs.env,
                _ => false,
            };
            if set {
                self.error(
                    local.pos,
                    format!(
                        "{} is not allowed in \"runs\" section because {} is a {ty} action. the action is defined at {}",
                        quote(prop),
                        quote(local.name),
                        quote(local.dir)
                    ),
                );
            }
        }
    }

    fn file_exists(&mut self, local: &Local, file: &str, prop: &str) {
        if file.is_empty() || local.base.join(file).exists() {
            return;
        }
        self.error(
            local.pos,
            format!(
                "file {} does not exist in {}. it is specified at {} key in \"runs\" section in {} action",
                quote(file),
                quote(local.dir),
                quote(prop),
                quote(local.name)
            ),
        );
    }

    fn check_docker_runs(&mut self, runs: &ActionRuns, local: &Local) {
        if runs.image.is_empty() {
            self.missing_prop(local, "image", "Docker");
        } else if !on_registry(&runs.image) {
            self.file_exists(local, &runs.image, "image");
            if Path::new(&runs.image).file_name().and_then(|n| n.to_str()) != Some("Dockerfile") {
                self.error(
                    local.pos,
                    format!(
                        "the local file {} referenced from \"image\" key must be named \"Dockerfile\" in {} action. the action is defined at {}",
                        quote(&runs.image),
                        quote(local.name),
                        quote(local.dir)
                    ),
                );
            }
        }
        self.file_exists(local, &runs.pre_entrypoint, "pre-entrypoint");
        self.file_exists(local, &runs.entrypoint, "entrypoint");
        self.file_exists(local, &runs.post_entrypoint, "post-entrypoint");
        self.invalid_props(
            runs,
            local,
            "Docker",
            &["main", "pre", "pre-if", "post", "post-if", "steps"],
        );
    }

    fn check_composite_runs(&mut self, runs: &ActionRuns, local: &Local) {
        if runs.steps.is_none() {
            self.missing_prop(local, "steps", "Composite");
        }
        self.invalid_props(
            runs,
            local,
            "Composite",
            &[
                "main",
                "pre",
                "pre-if",
                "post",
                "post-if",
                "image",
                "pre-entrypoint",
                "entrypoint",
                "post-entrypoint",
                "args",
                "env",
            ],
        );
    }

    fn check_javascript_runs(&mut self, runs: &ActionRuns, local: &Local) {
        if runs.main.is_empty() {
            self.missing_prop(local, "main", "JavaScript");
        } else {
            self.file_exists(local, &runs.main, "main");
        }
        for (file, condition, prop) in [
            (&runs.pre, &runs.pre_if, "pre"),
            (&runs.post, &runs.post_if, "post"),
        ] {
            self.file_exists(local, file, prop);
            if file.is_empty() && !condition.is_empty() {
                self.error(
                    local.pos,
                    format!(
                        "\"{prop}\" is required when \"{prop}-if\" is specified in \"runs\" section in {} action. the action is defined at {}",
                        quote(local.name),
                        quote(local.dir)
                    ),
                );
            }
        }
        self.invalid_props(
            runs,
            local,
            "JavaScript",
            &[
                "steps",
                "image",
                "pre-entrypoint",
                "entrypoint",
                "post-entrypoint",
                "args",
                "env",
            ],
        );
    }

    fn check_inputs(&mut self, meta: &ActionMetadata, exec: &ExecAction, pos: Pos, describe: &str) {
        let given = exec.inputs.as_ref();
        for (id, input) in given.into_iter().flatten() {
            match meta.inputs.get(id) {
                None => {
                    let names: Vec<&str> = meta.inputs.values().map(|i| i.name.as_str()).collect();
                    self.error(
                        input.name.pos,
                        format!(
                            "input {} is not defined in action {describe}. available inputs are {}",
                            quote(&input.name.value),
                            sorted_quotes(&names)
                        ),
                    );
                }
                Some(spec) if spec.deprecated && !spec.required => {
                    let mut message = format!(
                        "avoid using deprecated input {} in action {describe}",
                        quote(&input.name.value)
                    );
                    let note = NEWLINE_WITH_INDENT
                        .replace_all(spec.deprecation_message.trim_end_matches(['.', ' ']), " ");
                    if !note.is_empty() {
                        message.push_str(": ");
                        message.push_str(&note);
                    }
                    self.error(input.name.pos, message);
                }
                Some(_) => {}
            }
        }
        let required: Vec<&str> = meta
            .inputs
            .values()
            .filter(|i| i.required)
            .map(|i| i.name.as_str())
            .collect();
        for (id, input) in &meta.inputs {
            if input.required && !given.is_some_and(|g| g.contains_key(id)) {
                self.error(
                    pos,
                    format!(
                        "missing input {} which is required by action {describe}. all required inputs are {}",
                        quote(&input.name),
                        sorted_quotes(&required)
                    ),
                );
            }
        }
    }
}

struct Local<'a> {
    dir: &'a str,
    base: &'a Path,
    name: &'a str,
    pos: Pos,
}

impl Rule for Action {
    fn name(&self) -> &'static str {
        "action"
    }

    fn report(&mut self) -> &mut Report {
        &mut self.report
    }

    fn visit_step(&mut self, step: &Step) {
        let Some(Exec::Action(exec)) = &step.exec else {
            return;
        };
        let Some(uses) = &exec.uses else {
            return;
        };
        if uses.contains_expression() {
            return;
        }
        let spec = uses.value.as_str();
        if spec.starts_with("./") {
            self.check_local(spec, exec, uses.pos);
        } else if spec.starts_with("docker://") {
            self.check_docker(spec, uses.pos);
        } else {
            self.check_repo(spec, exec, uses.pos);
        }
    }
}

