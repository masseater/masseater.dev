use std::collections::BTreeMap;
use std::sync::LazyLock;

use serde::Deserialize;

use crate::entities::workflow::{Job, Matrix, RawValue, Text, contains_expression};
use crate::features::check_workflow::{CONFIG_NAME, Report, Rule};
use crate::shared::expression::ast::Expr;
use crate::shared::expression::lexer::Lexer;
use crate::shared::expression::parser::parse;
use crate::shared::text::quote;

#[derive(Deserialize)]
struct Hosted {
    label: String,
    os: String,
    image: String,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct SelfHosted {
    os: Vec<String>,
    other: Vec<String>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Runners {
    hosted: Vec<Hosted>,
    self_hosted: SelfHosted,
}

type Compat = u128;

const INVALID: Compat = 0;

struct Table {
    runners: Runners,
    compats: BTreeMap<String, Compat>,
}

static TABLE: LazyLock<Table> = LazyLock::new(|| {
    let runners: Runners = serde_json::from_str(include_str!("../../../../data/runners.json"))
        .expect("runners.json is generated by bin/generate-data.ts");
    let mut images: Vec<&str> = Vec::new();
    let mut compats = BTreeMap::new();
    for hosted in &runners.hosted {
        let index = images
            .iter()
            .position(|i| *i == hosted.image)
            .unwrap_or_else(|| {
                images.push(&hosted.image);
                images.len() - 1
            });
        compats.insert(hosted.label.to_lowercase(), 1 << index);
    }
    for os in &runners.self_hosted.os {
        let bits = runners
            .hosted
            .iter()
            .filter(|h| h.os == *os)
            .filter_map(|h| compats.get(&h.label.to_lowercase()))
            .fold(0, |acc, bits| acc | bits);
        compats.insert(os.clone(), bits);
    }
    Table { runners, compats }
});

fn labels_in_matrix(label: &Text, matrix: Option<&Matrix>) -> Vec<Text> {
    let Some(matrix) = matrix else {
        return Vec::new();
    };
    if !label.is_expression_assigned() {
        return Vec::new();
    }
    let trimmed = label.value.trim();
    let mut lexer = Lexer::new(trimmed.get(3..).unwrap_or_default());
    let Ok(Expr::ObjectDeref { receiver, property }) = parse(&mut lexer) else {
        return Vec::new();
    };
    let Expr::Variable { name, .. } = receiver.as_ref() else {
        return Vec::new();
    };
    if name != "matrix" {
        return Vec::new();
    }
    let text_of = |value: &RawValue| match value {
        RawValue::String { value, pos } if !contains_expression(value) => Some(Text {
            value: value.clone(),
            quoted: false,
            pos: *pos,
        }),
        _ => None,
    };
    let mut labels: Vec<Text> = matrix
        .rows
        .get(&property)
        .iter()
        .flat_map(|row| &row.values)
        .filter_map(text_of)
        .collect();
    for combination in matrix.include.iter().flat_map(|i| &i.combinations) {
        if let Some(assign) = combination.assigns.get(&property) {
            labels.extend(text_of(&assign.value));
        }
    }
    labels
}

#[derive(Default)]
pub struct RunnerLabel {
    report: Report,
    compats: Vec<(Compat, Text)>,
    known: Vec<String>,
}

impl RunnerLabel {
    pub fn new(known: Vec<String>) -> Self {
        Self {
            known,
            ..Self::default()
        }
    }

    fn verify(&mut self, label: &Text) -> Compat {
        let table = &*TABLE;
        let lower = label.value.to_lowercase();
        if let Some(compat) = table.compats.get(&lower) {
            return *compat;
        }
        if table
            .runners
            .self_hosted
            .other
            .iter()
            .any(|o| o.eq_ignore_ascii_case(&label.value))
        {
            return INVALID;
        }
        if self
            .known
            .iter()
            .any(|k| crate::shared::glob::path_match(k, &label.value))
        {
            return INVALID;
        }
        let all: Vec<&str> = table
            .runners
            .hosted
            .iter()
            .map(|h| h.label.as_str())
            .chain(table.runners.self_hosted.other.iter().map(String::as_str))
            .chain(table.runners.self_hosted.os.iter().map(String::as_str))
            .chain(self.known.iter().map(String::as_str))
            .collect();
        self.error(
            label.pos,
            format!(
                "label {} is unknown. available labels are {}. if it is a custom label for self-hosted runner, set list of labels in {CONFIG_NAME}",
                quote(&label.value),
                crate::shared::text::quotes(&all)
            ),
        );
        INVALID
    }

    fn check_conflict(&mut self, compat: Compat, label: &Text) -> bool {
        if let Some((_, previous)) = self.compats.iter().find(|(c, _)| c & compat == 0) {
            let message = format!(
                "label {} conflicts with label {} defined at {}. note: to run your job on each workers, use matrix",
                quote(&label.value),
                quote(&previous.value),
                previous.pos.describe()
            );
            self.error(label.pos, message);
            return false;
        }
        true
    }

    fn remember(&mut self, compat: Compat, label: &Text) {
        if !self.compats.iter().any(|(c, _)| *c == compat) {
            self.compats.push((compat, label.clone()));
        }
    }

    fn check_label_and_conflict(&mut self, label: &Text, matrix: Option<&Matrix>) {
        if label.contains_expression() {
            let labels = labels_in_matrix(label, matrix);
            let mut compats: Vec<Compat> = labels.iter().map(|l| self.verify(l)).collect();
            for (compat, label) in compats.iter_mut().zip(&labels) {
                if *compat != INVALID && !self.check_conflict(*compat, label) {
                    *compat = INVALID;
                }
            }
            for (compat, label) in compats.into_iter().zip(&labels) {
                if compat != INVALID {
                    self.remember(compat, label);
                }
            }
            return;
        }
        let compat = self.verify(label);
        if compat == INVALID || !self.check_conflict(compat, label) {
            return;
        }
        self.remember(compat, label);
    }
}

impl Rule for RunnerLabel {
    fn name(&self) -> &'static str {
        "runner-label"
    }

    fn report(&mut self) -> &mut Report {
        &mut self.report
    }

    fn visit_job_pre(&mut self, job: &Job) {
        let Some(runner) = &job.runs_on else {
            return;
        };
        let matrix = job.strategy.as_ref().and_then(|s| s.matrix.as_ref());
        if let [label] = runner.labels.as_slice() {
            if label.contains_expression() {
                for found in labels_in_matrix(label, matrix) {
                    self.verify(&found);
                }
            } else {
                self.verify(label);
            }
            return;
        }
        self.compats.clear();
        if let Some(expression) = &runner.labels_expr {
            self.check_label_and_conflict(expression, matrix);
        } else {
            for label in &runner.labels {
                self.check_label_and_conflict(label, matrix);
            }
        }
        self.compats.clear();
    }
}
