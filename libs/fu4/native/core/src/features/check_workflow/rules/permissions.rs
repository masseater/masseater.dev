use std::collections::BTreeMap;
use std::sync::LazyLock;

use crate::entities::workflow::{Job, Permissions as Section, Workflow};
use crate::features::check_workflow::{Report, Rule};
use crate::shared::text::{quote, quotes, sorted_quotes};

static SCOPES: LazyLock<BTreeMap<String, Vec<String>>> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../../data/permissions.json"))
        .expect("permissions.json is generated by bin/generate-data.ts")
});

#[derive(Default)]
pub struct Permissions {
    report: Report,
}

impl Permissions {
    fn check(&mut self, permissions: Option<&Section>) {
        let Some(permissions) = permissions else {
            return;
        };
        if let Some(all) = &permissions.all {
            if !matches!(all.value.as_str(), "write-all" | "read-all") {
                self.error(
                    all.pos,
                    format!(
                        "{} is invalid for permission for all the scopes. available values are \"read-all\", \"write-all\" or {{}}",
                        quote(&all.value)
                    ),
                );
            }
            return;
        }
        for scope in permissions.scopes.values() {
            let name = &scope.name.value;
            let Some(values) = SCOPES.get(name) else {
                let names: Vec<&String> = SCOPES.keys().collect();
                self.error(
                    scope.name.pos,
                    format!(
                        "unknown permission scope {}. all available permission scopes are {}",
                        quote(name),
                        sorted_quotes(&names)
                    ),
                );
                continue;
            };
            if !values.contains(&scope.value.value) {
                self.error(
                    scope.value.pos,
                    format!(
                        "{} is invalid as permission of scope {}. available values are {}",
                        quote(&scope.value.value),
                        quote(name),
                        quotes(values)
                    ),
                );
            }
        }
    }
}

impl Rule for Permissions {
    fn name(&self) -> &'static str {
        "permissions"
    }

    fn report(&mut self) -> &mut Report {
        &mut self.report
    }

    fn visit_job_pre(&mut self, job: &Job) {
        self.check(job.permissions.as_ref());
    }

    fn visit_workflow_pre(&mut self, workflow: &Workflow) {
        self.check(workflow.permissions.as_ref());
    }
}
