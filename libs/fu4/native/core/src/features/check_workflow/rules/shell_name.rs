use std::sync::LazyLock;

use serde::Deserialize;

use crate::entities::workflow::{Exec, Job, Runner, Step, Text, Workflow};
use crate::features::check_workflow::{Report, Rule};
use crate::shared::text::{quote, sorted_quotes};

#[derive(Deserialize)]
struct Shells {
    unix: Vec<String>,
    windows: Vec<String>,
}

static SHELLS: LazyLock<Shells> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../../data/shells.json"))
        .expect("shells.json is generated by bin/generate-data.ts")
});

#[derive(Clone, Copy, PartialEq, Eq, Default)]
enum Platform {
    #[default]
    Any,
    Unix,
    Windows,
}

fn available(platform: Platform) -> Vec<&'static str> {
    let shells = &*SHELLS;
    let mut names: Vec<&str> = match platform {
        Platform::Unix => shells.unix.iter().map(String::as_str).collect(),
        Platform::Windows => shells.windows.iter().map(String::as_str).collect(),
        Platform::Any => shells
            .unix
            .iter()
            .chain(&shells.windows)
            .map(String::as_str)
            .collect(),
    };
    names.sort_unstable();
    names.dedup();
    names
}

fn platform_of(runner: &Runner) -> Platform {
    let mut found = Platform::Any;
    for label in &runner.labels {
        let lower = label.value.to_lowercase();
        let kind = if lower.starts_with("windows-") || lower == "windows" {
            Platform::Windows
        } else if lower.starts_with("macos-")
            || lower.starts_with("ubuntu-")
            || lower == "macos"
            || lower == "linux"
        {
            Platform::Unix
        } else {
            continue;
        };
        if found != Platform::Any && found != kind {
            return Platform::Any;
        }
        found = kind;
    }
    found
}

#[derive(Default)]
pub struct ShellName {
    report: Report,
    platform: Platform,
}

impl ShellName {
    fn check(&mut self, shell: Option<&Text>) {
        let Some(shell) = shell else {
            return;
        };
        if shell.value.contains("{0}") || shell.contains_expression() {
            return;
        }
        let name = shell.value.to_lowercase();
        let names = available(self.platform);
        if names.contains(&name.as_str()) {
            return;
        }
        let known = available(Platform::Any).contains(&name.as_str());
        let on = match self.platform {
            Platform::Windows if known => " on Windows",
            Platform::Unix if known => " on macOS or Linux",
            _ => "",
        };
        self.error(
            shell.pos,
            format!(
                "shell name {} is invalid{on}. available names are {}",
                quote(&shell.value),
                sorted_quotes(&names)
            ),
        );
    }
}

impl Rule for ShellName {
    fn name(&self) -> &'static str {
        "shell-name"
    }

    fn report(&mut self) -> &mut Report {
        &mut self.report
    }

    fn visit_step(&mut self, step: &Step) {
        if let Some(Exec::Run(run)) = &step.exec {
            self.check(run.shell.as_ref());
        }
    }

    fn visit_job_pre(&mut self, job: &Job) {
        let Some(runner) = &job.runs_on else {
            return;
        };
        self.platform = platform_of(runner);
        let shell = job
            .defaults
            .as_ref()
            .and_then(|d| d.run.as_ref())
            .and_then(|r| r.shell.as_ref());
        self.check(shell);
    }

    fn visit_job_post(&mut self, _job: &Job) {
        self.platform = Platform::Any;
    }

    fn visit_workflow_pre(&mut self, workflow: &Workflow) {
        let shell = workflow
            .defaults
            .as_ref()
            .and_then(|d| d.run.as_ref())
            .and_then(|r| r.shell.as_ref());
        self.check(shell);
    }
}
