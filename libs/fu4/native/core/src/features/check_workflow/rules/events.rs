use std::collections::{BTreeMap, HashSet};
use std::sync::LazyLock;

use crate::entities::workflow::{
    CallInputType, DispatchInput, DispatchInputType, Event, EventFilter, Text, WebhookEvent,
    Workflow, WorkflowCallEvent,
};
use crate::features::check_workflow::{Report, Rule};
use crate::shared::cron;
use crate::shared::text::{quote, sorted_quotes};
use crate::shared::yaml::{Pos, parse_go_float};

static WEBHOOKS: LazyLock<BTreeMap<String, Option<Vec<String>>>> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../../data/webhooks.json"))
        .expect("webhooks.json is generated by bin/generate-data.ts")
});

const MAX_DISPATCH_INPUTS: usize = 25;
const MIN_INTERVAL: u64 = 60 * 5;

fn is_empty(filter: Option<&EventFilter>) -> bool {
    filter.is_none_or(|f| f.values.is_empty())
}

fn float_error(text: &str) -> Option<String> {
    parse_go_float(text).is_none().then(|| {
        format!(
            "strconv.ParseFloat: parsing {}: invalid syntax",
            quote(text)
        )
    })
}

#[derive(Default)]
pub struct Events {
    report: Report,
}

impl Events {
    fn check_cron(&mut self, spec: &Text) {
        match cron::parse(&spec.value) {
            Err(error) => self.error(
                spec.pos,
                format!(
                    "invalid CRON format {} in schedule event: {error}",
                    quote(&spec.value)
                ),
            ),
            Ok(schedule) => {
                if let Some(interval) = schedule.interval_seconds()
                    && interval < MIN_INTERVAL
                {
                    self.error(
                        spec.pos,
                        format!(
                            "scheduled job runs too frequently. it runs once per {interval} seconds. the shortest interval is once every 5 minutes"
                        ),
                    );
                }
            }
        }
    }

    fn check_timezone(&mut self, timezone: &Text) {
        let value = &timezone.value;
        let valid = !value.is_empty()
            && !value.eq_ignore_ascii_case("utc")
            && !value.eq_ignore_ascii_case("local")
            && jiff::tz::TimeZone::get(value).is_ok();
        if !valid {
            self.error(
                timezone.pos,
                format!(
                    "invalid timezone {} in schedule event. it must be a valid IANA timezone name",
                    quote(value)
                ),
            );
        }
    }

    fn filter_not_available(&mut self, pos: Pos, filter: &str, hook: &str, available: &[&str]) {
        let noun = if available.len() < 2 {
            "event"
        } else {
            "events"
        };
        self.error(
            pos,
            format!(
                "{} filter is not available for {hook} event. it is only for {} {noun}",
                quote(filter),
                available.join(", ")
            ),
        );
    }

    fn check_exclusive(
        &mut self,
        filter: Option<&EventFilter>,
        ignore: Option<&EventFilter>,
        hook: &str,
        available: &[&str],
    ) {
        if available.contains(&hook) {
            if let (Some(filter), Some(ignore)) = (filter, ignore)
                && !filter.values.is_empty()
                && !ignore.values.is_empty()
            {
                let pos = if filter.name.pos.is_before(&ignore.name.pos) {
                    ignore.name.pos
                } else {
                    filter.name.pos
                };
                self.error(
                    pos,
                    format!(
                        "both {} and {} filters cannot be used for the same event {}. note: use '!' to negate patterns",
                        quote(&filter.name.value),
                        quote(&ignore.name.value),
                        quote(hook)
                    ),
                );
            }
            return;
        }
        for item in [filter, ignore].into_iter().flatten() {
            if !is_empty(Some(item)) {
                self.filter_not_available(item.name.pos, &item.name.value, hook, available);
            }
        }
    }

    fn check_types(&mut self, hook: &Text, types: &[Text], expected: &[String]) {
        if expected.is_empty() && !types.is_empty() {
            self.error(
                hook.pos,
                format!(
                    "\"types\" cannot be specified for {} Webhook event",
                    quote(&hook.value)
                ),
            );
            return;
        }
        for kind in types {
            if !expected.contains(&kind.value) {
                self.error(
                    kind.pos,
                    format!(
                        "invalid activity type {} for {} Webhook event. available types are {}",
                        quote(&kind.value),
                        quote(&hook.value),
                        sorted_quotes(expected)
                    ),
                );
            }
        }
    }

    fn check_webhook(&mut self, event: &WebhookEvent) {
        let hook = event.hook.value.as_str();
        let Some(types) = WEBHOOKS.get(hook) else {
            self.error(
                event.pos,
                format!(
                    "unknown Webhook event {}. see https://docs.github.com/en/actions/reference/workflows-and-actions/events-that-trigger-workflows#webhook-events for list of all Webhook event names",
                    quote(hook)
                ),
            );
            return;
        };
        if let Some(types) = types {
            self.check_types(&event.hook, &event.types, types);
        }
        if hook == "workflow_run" {
            if event.workflows.is_empty() {
                self.error(
                    event.pos,
                    "no workflow is configured for \"workflow_run\" event".to_owned(),
                );
            }
        } else if !event.workflows.is_empty() {
            self.error(
                event.pos,
                format!(
                    "\"workflows\" cannot be configured for {} event. it is only for workflow_run event",
                    quote(hook)
                ),
            );
        }
        self.check_exclusive(
            event.paths.as_ref(),
            event.paths_ignore.as_ref(),
            hook,
            &["push", "pull_request", "pull_request_target"],
        );
        self.check_exclusive(
            event.branches.as_ref(),
            event.branches_ignore.as_ref(),
            hook,
            &[
                "merge_group",
                "push",
                "pull_request",
                "pull_request_target",
                "workflow_run",
            ],
        );
        self.check_exclusive(
            event.tags.as_ref(),
            event.tags_ignore.as_ref(),
            hook,
            &["push"],
        );
    }

    fn check_workflow_call(&mut self, event: &WorkflowCallEvent) {
        for input in &event.inputs {
            let Some(default) = &input.default else {
                continue;
            };
            if !default.contains_expression() {
                match input.kind {
                    CallInputType::Number => {
                        if let Some(error) = float_error(&default.value) {
                            self.error(
                                default.pos,
                                format!(
                                    "input of workflow_call event {} is typed as number but its default value {} cannot be parsed as a float number: {error}",
                                    quote(&input.name.value),
                                    quote(&default.value)
                                ),
                            );
                        }
                    }
                    CallInputType::Boolean => {
                        let lower = default.value.to_lowercase();
                        if lower != "true" && lower != "false" {
                            self.error(
                                default.pos,
                                format!(
                                    "input of workflow_call event {} is typed as boolean. its default value must be true or false but got {}",
                                    quote(&input.name.value),
                                    quote(&default.value)
                                ),
                            );
                        }
                    }
                    _ => {}
                }
            }
            if input.is_required() {
                self.error(
                    default.pos,
                    format!(
                        "input {} of workflow_call event has the default value {}, but it is also required. if an input is marked as required, its default value will never be used",
                        quote(&input.name.value),
                        quote(&default.value)
                    ),
                );
            }
        }
    }

    fn check_dispatch_input(&mut self, name: &str, input: &DispatchInput) {
        if input.kind == DispatchInputType::Choice {
            if input.options.is_empty() {
                self.error(
                    input.name.pos,
                    format!(
                        "input type of {} is \"choice\" but \"options\" is not set",
                        quote(name)
                    ),
                );
                return;
            }
            let mut seen = HashSet::new();
            for option in &input.options {
                if !seen.insert(option.value.as_str()) {
                    self.error(
                        option.pos,
                        format!(
                            "option {} is duplicated in options of {} input",
                            quote(&option.value),
                            quote(name)
                        ),
                    );
                }
            }
            if let Some(default) = &input.default
                && !seen.contains(default.value.as_str())
            {
                let options: Vec<&str> = input.options.iter().map(|o| o.value.as_str()).collect();
                let listed = crate::shared::text::quotes(&options);
                self.error(
                    default.pos,
                    format!(
                        "default value {} of {} input is not included in its options {}",
                        quote(&default.value),
                        quote(name),
                        quote(&listed)
                    ),
                );
            }
            return;
        }
        if !input.options.is_empty() {
            self.error(
                input.name.pos,
                format!(
                    "\"options\" can not be set to {} input because its input type is not \"choice\"",
                    quote(name)
                ),
            );
        }
        let Some(default) = &input.default else {
            return;
        };
        match input.kind {
            DispatchInputType::Number => {
                if let Some(error) = float_error(&default.value) {
                    self.error(
                        default.pos,
                        format!(
                            "type of {} input is \"number\" but its default value {} cannot be parsed as a float number: {error}",
                            quote(&input.name.value),
                            quote(&default.value)
                        ),
                    );
                }
            }
            DispatchInputType::Boolean => {
                let lower = default.value.to_lowercase();
                if lower != "true" && lower != "false" {
                    self.error(
                        default.pos,
                        format!(
                            "type of {} input is \"boolean\". its default value {} must be \"true\" or \"false\"",
                            quote(name),
                            quote(&default.value)
                        ),
                    );
                }
            }
            _ => {}
        }
    }

    fn check_event(&mut self, event: &Event) {
        match event {
            Event::Schedule { schedules, .. } => {
                for schedule in schedules {
                    self.check_cron(&schedule.cron);
                    if let Some(timezone) = &schedule.timezone {
                        self.check_timezone(timezone);
                    }
                }
            }
            Event::WorkflowDispatch { inputs, pos } => {
                for (name, input) in inputs {
                    self.check_dispatch_input(name, input);
                }
                if inputs.len() > MAX_DISPATCH_INPUTS {
                    self.error(
                        *pos,
                        format!(
                            "maximum number of inputs for \"workflow_dispatch\" event is 25 but {} inputs are provided. see https://docs.github.com/en/actions/using-workflows/events-that-trigger-workflows#providing-inputs",
                            inputs.len()
                        ),
                    );
                }
            }
            Event::WorkflowCall(call) => self.check_workflow_call(call),
            Event::Webhook(hook) => self.check_webhook(hook),
            Event::RepositoryDispatch { .. } | Event::ImageVersion { .. } => {}
        }
    }
}

impl Rule for Events {
    fn name(&self) -> &'static str {
        "events"
    }

    fn report(&mut self) -> &mut Report {
        &mut self.report
    }

    fn visit_workflow_pre(&mut self, workflow: &Workflow) {
        for event in workflow.on.iter().flatten() {
            self.check_event(event);
        }
    }
}
