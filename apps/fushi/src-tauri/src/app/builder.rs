use desktop_shell::{Setup, Shell, open_window, screen_port};
use tauri::App;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

use crate::features::{keep_library, read_baselines};

const SCREEN_PORT: u16 = 47_251;
const CAPABILITY: &str = include_str!("../../capabilities/default.json");

fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Result)
        .commands(collect_commands![
            keep_library::load_library,
            keep_library::save_library,
            read_baselines::list_baselines,
            read_baselines::read_baseline,
        ])
}

fn setup(app: &App, port: u16) -> Setup {
    open_window(app, port, CAPABILITY)
}

pub fn run() -> tauri::Result<()> {
    let builder = builder();
    let port = screen_port(SCREEN_PORT)?;
    desktop_shell::builder(&Shell {
        name: "ふし",
        window: "main",
        port,
    })
    .invoke_handler(desktop_shell::traced_commands(builder.invoke_handler()))
    .setup(move |app| setup(app, port))
    .run(tauri::generate_context!())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::PathBuf;

    use specta_typescript::Typescript;

    use tauri::ipc::{CallbackFn, InvokeBody};
    use tauri::test::{INVOKE_KEY, get_ipc_response, mock_builder};
    use tauri::webview::InvokeRequest;
    use tauri::{WebviewUrl, WebviewWindowBuilder};

    use super::{CAPABILITY, SCREEN_PORT, builder};

    const COMMAND: &str = "list_baselines";
    const BINDINGS: &str = "../src/shared/api/generated/bindings.ts";

    #[test]
    fn typescript_bindings_are_current() {
        let committed = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(BINDINGS);
        let generated =
            std::env::temp_dir().join(format!("fushi-bindings-{}.ts", std::process::id()));
        builder()
            .export(
                Typescript::default().header("// @generated by apps/fushi/src-tauri. Do not edit."),
                &generated,
            )
            .expect("export bindings");
        let fresh = fs::read_to_string(&generated).expect("read generated bindings");
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            fs::write(&committed, &fresh).expect("write bindings");
        }
        let current = fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            current == fresh,
            "{BINDINGS} is stale: run UPDATE_BINDINGS=1 cargo test -p fushi"
        );
    }

    #[test]
    fn only_the_origin_the_screen_is_served_from_may_call_commands() {
        let app = mock_builder()
            .build(tauri::generate_context!(test = true))
            .expect("app");
        let window = WebviewWindowBuilder::new(&app, "main", WebviewUrl::default())
            .build()
            .expect("window");
        let allowed = |origin: String| {
            let answer = get_ipc_response(
                &window,
                InvokeRequest {
                    cmd: COMMAND.into(),
                    callback: CallbackFn(0),
                    error: CallbackFn(1),
                    url: origin.parse().expect("origin"),
                    body: InvokeBody::default(),
                    headers: tauri::http::HeaderMap::default(),
                    invoke_key: INVOKE_KEY.to_owned(),
                },
            );
            answer
                .err()
                .and_then(|error| error.as_str().map(str::to_owned))
                == Some(format!("Command {COMMAND} not found"))
        };
        let served = format!("http://127.0.0.1:{SCREEN_PORT}/");
        let other = format!("http://127.0.0.1:{}/", SCREEN_PORT + 1);
        assert!(!allowed(served.clone()));
        desktop_shell::allow_screen(app.handle(), SCREEN_PORT, CAPABILITY).expect("capability");
        assert!(allowed(served));
        assert!(!allowed(other));
    }
}
