import { Ruleset, Zone, providers, state } from "@alchemy.run/cloudflare";
import { Stack } from "alchemy";
import type { CompiledStack } from "alchemy";
import { adopt } from "alchemy/AdoptPolicy";
import { Effect, Record as Rec, pipe } from "effect";
import type { ConfigError } from "effect/Config";

import { PREFIX } from "./app-name.ts";
import { SECURITY_HEADERS } from "./security-headers.ts";
import { site } from "./src/shared/config/site.ts";

const DOMAIN = new URL(site.url).hostname;

const CLOUDFLARE_RESPONSES =
  'cf.response.error_type eq "waf" or starts_with(http.request.uri.path, "/cdn-cgi/styles/")';

const CLOUDFLARE_RESPONSE_HEADERS = {
  ...SECURITY_HEADERS,
  "Content-Security-Policy":
    "default-src 'none'; style-src 'self'; img-src 'self' data:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
} as const;

const stack: Effect.Effect<CompiledStack, ConfigError> & Readonly<{ stackName: string }> = Stack(
  `${PREFIX}zone`,
  { providers: providers(), state: state() },
  Effect.gen(function* zone() {
    const owned = yield* Zone.Zone("Zone", { name: DOMAIN }).pipe(adopt(true));
    yield* Ruleset.Ruleset("CloudflareResponseHeaders", {
      zone: owned,
      name: `${PREFIX}cloudflare-response-headers`,
      phase: "http_response_headers_transform",
      rules: [
        {
          description: "Add security headers to responses generated by Cloudflare",
          expression: CLOUDFLARE_RESPONSES,
          action: "rewrite",
          actionParameters: {
            headers: pipe(
              CLOUDFLARE_RESPONSE_HEADERS,
              Rec.map((value) => ({ operation: "set", value })),
            ),
          },
        },
      ],
    });
  }),
);

export default stack;
