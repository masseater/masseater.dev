use std::path::PathBuf;
use std::sync::Arc;

use desktop_shell::{Setup, Shell, open_window, screen_port};
use media_notes::{Setting, Site, media_notes};
use tauri::{App, Emitter, Manager, async_runtime};
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

use super::commands;
use super::mcp_server as mcp;
use super::workshop::Workshop;
use crate::entities::gpu_runtime::GpuRuntime;
use crate::entities::job::Jobs;
use crate::entities::song::Library;
use crate::features::repair_titles::repair_titles;

const SITES: &[Site] = &[Site::Youtube, Site::Niconico, Site::Soundcloud, Site::File];
const SCREEN_PORT: u16 = 47_241;
const CHANGED: &str = "yogoto://changed";
const LIBRARY: &str = "library";
const CUDA_RUNTIME: &str = "cuda-runtime.json";

fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Result)
        .commands(collect_commands![
            commands::list_songs,
            commands::song_folder,
            commands::remove_song,
            commands::list_models,
            commands::list_jobs,
            commands::import_song,
            commands::separate_song,
            commands::analyze_song,
            commands::choose_audio_files,
            media_notes::mcp_access,
        ])
}

fn repair(app: &App, library: Library, client: reqwest::Client, cache: PathBuf) {
    let handle = app.handle().clone();
    async_runtime::spawn(async move {
        match repair_titles(&library, &client, &cache).await {
            Ok(0) => {}
            Ok(repaired) => {
                tracing::info!(repaired, "garbled titles repaired");
                let _ = handle.emit(CHANGED, ());
            }
            Err(failure) => tracing::error!(%failure, "garbled titles could not be repaired"),
        }
    });
}

fn setup(app: &App, port: u16) -> Setup {
    let data = app.path().app_local_data_dir()?;
    let cache = app.path().app_cache_dir()?;
    let notes = media_notes(&Setting {
        name: "yogoto",
        version: env!("CARGO_PKG_VERSION"),
        data: &data,
        sites: SITES,
        port: mcp::PORT,
    })?;
    let handle = app.handle().clone();
    let jobs = Jobs::new(Arc::new(move || {
        let _ = handle.emit(CHANGED, ());
    }));
    let client = audio_fetch::shared::http::client()?;
    let manifest = app.path().resource_dir()?.join(CUDA_RUNTIME);
    let gpu = GpuRuntime::prepare(client.clone(), manifest.is_file().then_some(manifest));
    let library = Library::open(&data.join(LIBRARY))?;
    repair(app, library.clone(), client.clone(), cache.clone());
    let workshop = Workshop::start(library, client, cache, jobs, gpu);
    let serving = mcp::Serving {
        workshop: workshop.clone(),
        token: notes.mcp.token.clone(),
    };
    async_runtime::spawn(async move {
        if let Err(failure) = mcp::serve(serving).await {
            tracing::error!(%failure, "mcp server stopped");
        }
    });
    app.manage(notes);
    app.manage(workshop);
    open_window(app, port)
}

pub fn run() -> tauri::Result<()> {
    let builder = builder();
    let port = screen_port(SCREEN_PORT)?;
    desktop_shell::builder(&Shell {
        name: "よごと",
        window: "main",
        port,
    })
    .invoke_handler(desktop_shell::traced_commands(builder.invoke_handler()))
    .setup(move |app| setup(app, port))
    .run(tauri::generate_context!())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::PathBuf;

    use specta_typescript::Typescript;

    use super::builder;

    const BINDINGS: &str = "../src/shared/api/generated/bindings.ts";

    #[test]
    fn typescript_bindings_are_current() {
        let committed = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(BINDINGS);
        let generated =
            std::env::temp_dir().join(format!("yogoto-bindings-{}.ts", std::process::id()));
        builder()
            .export(
                Typescript::default()
                    .header("// @generated by apps/yogoto/src-tauri. Do not edit."),
                &generated,
            )
            .expect("export bindings");
        let fresh = fs::read_to_string(&generated).expect("read generated bindings");
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            if let Some(parent) = committed.parent() {
                fs::create_dir_all(parent).expect("bindings folder");
            }
            fs::write(&committed, &fresh).expect("write bindings");
        }
        let current = fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            current == fresh,
            "{BINDINGS} is stale: run UPDATE_BINDINGS=1 cargo test -p yogoto"
        );
    }
}
