use tauri::{App, Manager, Url, WebviewUrl, WebviewWindowBuilder, Wry, async_runtime};
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

mod commands;
mod failure;
mod mcp;
pub mod protocol;
mod song;
mod source;
mod store;

const WINDOW: &str = "main";

fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Result)
        .commands(collect_commands![
            commands::list_marks,
            commands::save_mark,
            commands::remove_mark,
            commands::song_at,
            commands::mcp_access,
        ])
}

type Setup = Result<(), Box<dyn std::error::Error>>;

fn free_port() -> std::io::Result<u16> {
    Ok(std::net::TcpListener::bind((local_mcp::HOST, 0))?
        .local_addr()?
        .port())
}

fn served_at(port: u16) -> Result<WebviewUrl, url::ParseError> {
    if tauri::is_dev() {
        return Ok(WebviewUrl::default());
    }
    Ok(WebviewUrl::External(Url::parse(&format!(
        "http://{}:{port}",
        local_mcp::HOST
    ))?))
}

fn open_window(app: &App, port: u16) -> Setup {
    let mut config = app
        .config()
        .app
        .windows
        .first()
        .cloned()
        .ok_or("tauri.conf.json has no window")?;
    config.url = served_at(port)?;
    WebviewWindowBuilder::from_config(app, &config)?.build()?;
    Ok(())
}

fn setup(app: &App, port: u16) -> Setup {
    let data = app.path().app_local_data_dir()?;
    let state = commands::shirushi(&data).map_err(|failure| failure.message)?;
    let serving = (state.store.clone(), state.mcp_token.clone());
    async_runtime::spawn(async move {
        let (store, token) = serving;
        if let Err(failure) = mcp::serve(store, token).await {
            eprintln!("mcp server stopped: {failure}");
        }
    });
    app.manage(state);
    open_window(app, port)
}

fn served(app: tauri::Builder<Wry>, port: u16) -> tauri::Builder<Wry> {
    if tauri::is_dev() {
        return app;
    }
    app.plugin(
        tauri_plugin_localhost::Builder::new(port)
            .host(local_mcp::HOST)
            .build(),
    )
}

pub fn run() -> tauri::Result<()> {
    let builder = builder();
    let port = free_port()?;
    let single = tauri::Builder::default().plugin(tauri_plugin_single_instance::init(
        |app, _arguments, _cwd| {
            if let Some(window) = app.get_webview_window(WINDOW) {
                let _ = window.set_focus();
            }
        },
    ));
    served(single, port)
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| setup(app, port))
        .run(tauri::generate_context!())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::PathBuf;

    use specta_typescript::Typescript;

    use super::builder;

    const BINDINGS: &str = "../src/shared/api/generated/bindings.ts";

    #[test]
    fn typescript_bindings_are_current() {
        let committed = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(BINDINGS);
        let generated =
            std::env::temp_dir().join(format!("shirushi-bindings-{}.ts", std::process::id()));
        builder()
            .export(
                Typescript::default()
                    .header("// @generated by apps/shirushi/src-tauri. Do not edit."),
                &generated,
            )
            .expect("export bindings");
        let fresh = fs::read_to_string(&generated).expect("read generated bindings");
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            fs::write(&committed, &fresh).expect("write bindings");
        }
        let current = fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            current == fresh,
            "{BINDINGS} is stale: run UPDATE_BINDINGS=1 cargo test -p shirushi"
        );
    }
}
